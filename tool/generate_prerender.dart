/// HTML-escapes text for both text and quoted-attribute contexts. `'` is
/// escaped as well so a stray single quote can never open an attribute in a
/// context this file does not control.
String escapeHtml(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');

// ── Seed SQL parsing ──────────────────────────────────────────────────────

class SeedRow {
  final String id;
  final List<String> fields;
  SeedRow({required this.id, required this.fields});
}

/// Extracts every VALUES tuple of `INSERT INTO <table>` as a field list.
/// [expected] is the column count, used only as an assertion signal.
List<SeedRow> parseTable(String sql, String table, int expected) {
  final insertAt = sql.indexOf('INSERT INTO $table');
  if (insertAt < 0) throw StateError('Table $table not found in seed');
  final valuesAt = sql.indexOf('VALUES', insertAt);
  final end = sql.indexOf('ON CONFLICT', valuesAt);
  final region = sql.substring(valuesAt + 'VALUES'.length, end < 0 ? sql.length : end);

  final rows = <SeedRow>[];
  final scanner = _Scanner(region);
  while (true) {
    scanner.skipToNextTuple();
    if (scanner.atEnd) break;
    if (scanner.peek != '(') break;
    final fields = scanner.readTuple();
    if (fields.length != expected) {
      throw StateError('$table tuple has ${fields.length} fields, expected $expected: ${fields.first}');
    }
    rows.add(SeedRow(id: fields[0], fields: fields));
  }
  return rows;
}

class _Scanner {
  final String _s;
  int _i = 0;
  _Scanner(this._s);

  bool get atEnd => _i >= _s.length;
  String get peek => _s[_i];

  void skipToNextTuple() {
    while (!atEnd) {
      final c = _s[_i];
      if (c == '\n' || c == ' ' || c == '\t' || c == '\r' || c == ',') {
        _i++;
      } else if (c == '-' && _i + 1 < _s.length && _s[_i + 1] == '-') {
        while (!atEnd && _s[_i] != '\n') {
          _i++;
        }
      } else {
        return;
      }
    }
  }

  List<String> readTuple() {
    final fields = <String>[];
    _i++; // consume '('
    while (true) {
      _skipWsAndComments();
      final value = _readValue();
      fields.add(value);
      _skipWsAndComments();
      if (_s[_i] == ',') {
        _i++;
        continue;
      }
      if (_s[_i] == ')') {
        _i++;
        break;
      }
      throw StateError('Unexpected "${_s[_i]}" at $_i in tuple');
    }
    return fields;
  }

  void _skipWsAndComments() {
    while (!atEnd) {
      final c = _s[_i];
      if (c == ' ' || c == '\n' || c == '\t' || c == '\r') {
        _i++;
      } else if (c == '-' && _i + 1 < _s.length && _s[_i + 1] == '-') {
        while (!atEnd && _s[_i] != '\n') {
          _i++;
        }
      } else {
        return;
      }
    }
  }

  String _readValue() {
    final c = _s[_i];
    if (c == "'") {
      _i++; // consume opening quote; _readString starts at content
      return _readString(isE: false);
    }
    if ((c == 'E' || c == 'e') && _i + 1 < _s.length && _s[_i + 1] == "'") {
      _i += 2;
      return _readString(isE: true);
    }
    if (c == 'A' && _s.startsWith('ARRAY', _i)) {
      return _readArray();
    }
    // Bare token: NULL, number, boolean — until delimiter.
    final start = _i;
    while (!atEnd) {
      final ch = _s[_i];
      if (ch == ',' || ch == ')' || ch == '\n') break;
      _i++;
    }
    return _s.substring(start, _i).trim();
  }

  String _readString({required bool isE}) {
    final buf = StringBuffer();
    while (true) {
      final c = _s[_i];
      if (c == "'") {
        if (_i + 1 < _s.length && _s[_i + 1] == "'") {
          buf.write("'");
          _i += 2;
          continue;
        }
        _i++; // closing quote
        break;
      }
      if (isE && c == r'\') {
        _i++;
        final n = _s[_i];
        switch (n) {
          case 'n':
            buf.write('\n');
            break;
          case 't':
            buf.write('\t');
            break;
          case r'\':
            buf.write(r'\');
            break;
          default:
            buf.write(n);
        }
        _i++;
        continue;
      }
      buf.write(c);
      _i++;
    }
    _stripCast();
    return buf.toString();
  }

  String _readArray() {
    final start = _i;
    while (_s[_i] != '[') {
      _i++;
    }
    var depth = 0;
    while (true) {
      final c = _s[_i];
      if (c == '[') {
        depth++;
      } else if (c == ']') {
        depth--;
        if (depth == 0) {
          _i++;
          break;
        }
      } else if (c == "'") {
        _i++;
        _readString(isE: false);
        continue;
      }
      _i++;
    }
    return _s.substring(start, _i);
  }

  void _stripCast() {
    var j = _i;
    while (j < _s.length && (_s[j] == ' ')) {
      j++;
    }
    if (j + 1 < _s.length && _s[j] == ':' && _s[j + 1] == ':') {
      j += 2;
      while (j < _s.length && (_s[j] == '_' || _isAlnum(_s[j]))) {
        j++;
      }
      _i = j;
    }
  }

  bool _isAlnum(String c) =>
      (c.codeUnitAt(0) >= 48 && c.codeUnitAt(0) <= 57) ||
      (c.codeUnitAt(0) >= 65 && c.codeUnitAt(0) <= 90) ||
      (c.codeUnitAt(0) >= 97 && c.codeUnitAt(0) <= 122);
}

// ── Sitemap spot-check (>=5 article canonicals vs seed) ───────────────────

void _spotCheckSitemap(List<ArticleModel> posts) {
  final sitemap = File(_sitemapPath).existsSync()
      ? File(_sitemapPath).readAsStringSync()
      : '';
  final sitemapSlugs = RegExp(r'/article/([a-z0-9-]+)')
      .allMatches(sitemap)
      .map((m) => m.group(1)!)
      .toSet();
  final seedSlugs = posts.map((p) => p.slug).toSet();

  stdout.writeln('\nSitemap vs seed article check '
      '(${sitemapSlugs.length} in sitemap, ${seedSlugs.length} published in seed):');
  var checked = 0;
  for (final p in posts) {
    final canonical = SeoMeta.forArticle(p).canonicalUrl;
    final ok = sitemapSlugs.contains(p.slug) &&
        canonical == '${SiteConfig.domain}/article/${p.slug}';
    stdout.writeln('  ${ok ? "OK " : "MISS"} /article/${p.slug}  canonical=$canonical');
    if (++checked >= 6) break;
  }
  final missingFromSitemap = seedSlugs.difference(sitemapSlugs);
  if (missingFromSitemap.isNotEmpty) {
    stdout.writeln('  WARNING: published but absent from sitemap.xml: $missingFromSitemap');
  }
}
