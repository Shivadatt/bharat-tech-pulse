// Offline prerenderer for Bharat Tech Pulse (Flutter Web / CanvasKit).
//
// WHY THIS EXISTS: Flutter Web paints to a <canvas>, so a crawler that does not
// run JavaScript (Bing, most social scrapers, Lighthouse SEO audits) receives an
// empty shell whose <head> carries only the HOME page metadata — every article
// deep link would report the wrong title/OG image. Googlebot does render JS and
// sees SeoService's runtime tags, but the rest of the ecosystem does not.
//
// WHAT IT DOES: reads the deterministic editorial seed
// (supabase/migrations/006_seed_data.sql — NO network, NO database), rebuilds the
// very same [ArticleModel]/[CategoryModel] objects the app hydrates from
// Supabase, and emits a static HTML shell per published article and per category
// under build/web/. All head metadata comes from [SeoMeta] — the same pure
// calculator `SeoService` uses at runtime — so a JS and a no-JS crawler cannot
// be shown different titles, canonicals or structured data.
//
// USAGE (run AFTER `flutter build web`, since build/web is regenerated by it):
//   dart tool/generate_prerender.dart [--out build/web]
// It never overwrites build/web/index.html (the Flutter entry point), only adds
// article/<slug>/ and <category>/ sub-shells.
//
// This file must stay free of `flutter/` and `package:get` imports: it is run
// with `dart run`, not as a Flutter entry point.

import 'dart:convert';
import 'dart:io';

import 'package:india_tech_web/app/config/site_config.dart';
import 'package:india_tech_web/core/seo/seo_meta.dart';
import 'package:india_tech_web/core/utils/date_formatter.dart';
import 'package:india_tech_web/data/models/article_model.dart';
import 'package:india_tech_web/data/models/author_model.dart';
import 'package:india_tech_web/data/models/category_model.dart';

const String _seedPath = 'supabase/migrations/006_seed_data.sql';
const String _sitemapPath = 'web/sitemap.xml';

void main(List<String> args) {
  final outRoot = _flag(args, '--out') ?? 'build/web';
  final seed = File(_seedPath).readAsStringSync();
  final data = SeedData.parse(seed);

  if (data.publishedPosts.isEmpty) {
    stderr.writeln('Parsed 0 published posts — aborting (seed format changed?).');
    exit(1);
  }

  final dir = Directory(outRoot);
  if (!dir.existsSync()) dir.createSync(recursive: true);

  var articles = 0, cats = 0;
  for (final article in data.publishedPosts) {
    final html = buildArticleShell(article);
    final d = Directory('$outRoot/article/${article.slug}')
      ..createSync(recursive: true);
    File('${d.path}/index.html').writeAsStringSync(html);
    articles++;
  }

  for (final cat in data.categories) {
    final html = buildCategoryShell(cat);
    final d = Directory('$outRoot/${cat.slug}')..createSync(recursive: true);
    File('${d.path}/index.html').writeAsStringSync(html);
    cats++;
  }

  _spotCheckSitemap(data.publishedPosts);

  stdout.writeln(
      'Prerendered $articles article shells and $cats category shells into $outRoot/');
}

String? _flag(List<String> args, String name) {
  final i = args.indexOf(name);
  if (i >= 0 && i + 1 < args.length) return args[i + 1];
  return null;
}

// ── Parsed seed ───────────────────────────────────────────────────────────

/// The editorial rows of migration 006, rebuilt as the app's own models.
class SeedData {
  final List<CategoryModel> categories;
  final List<AuthorModel> authors;
  final List<ArticleModel> publishedPosts;

  const SeedData({
    required this.categories,
    required this.authors,
    required this.publishedPosts,
  });

  // Column order of the two `INSERT INTO public.posts` / `categories` /
  // `authors` statements in 006_seed_data.sql, kept as named indexes so the
  // field access below is readable.
  static const int _postId = 0;
  static const int _postAuthorId = 2;
  static const int _postCategoryId = 3;
  static const int _postTitle = 4;
  static const int _postSlug = 5;
  static const int _postExcerpt = 6;
  static const int _postContent = 7;
  static const int _postFeaturedImage = 8;
  static const int _postThumbnail = 9;
  static const int _postStatus = 10;
  static const int _postPublishedAt = 11;
  static const int _postReadingTime = 13;
  static const int _postSeoTitle = 14;
  static const int _postSeoDescription = 15;
  static const int _postCanonicalUrl = 16;
  static const int _postOgTitle = 17;
  static const int _postOgDescription = 18;
  static const int _postOgImage = 19;
  static const int _postIsFeatured = 20;
  static const int _postIsTrending = 21;
  static const int _postIsPopular = 22;
  static const int _postViewCount = 23;
  static const int _postSubcategory = 24;
  static const int _postKeyTakeaways = 25;
  static const int _postFaqs = 26;
  static const int _postToc = 27;
  static const int _postUpdatedAt = 29;

  static SeedData parse(String sql) {
    final categories = <String, CategoryModel>{};
    for (final r in parseTable(sql, 'public.categories', 12)) {
      categories[r.id] = seedToCategory(r);
    }
    final authors = <String, AuthorModel>{};
    for (final r in parseTable(sql, 'public.authors', 10)) {
      authors[r.id] = seedToAuthor(r);
    }

    // tags + post_tags: the runtime reads them through PostgREST's many-to-many
    // embed, and SeoSchema puts them in the BlogPosting `keywords`. The shell
    // must do the same or the two graphs differ.
    final tagSlugById = <String, String>{};
    for (final r in parseTable(sql, 'public.tags', 4)) {
      tagSlugById[r.fields[0]] = r.fields[3];
    }
    final tagsByPost = <String, List<String>>{};
    for (final r in parseTable(sql, 'public.post_tags', 2)) {
      final slug = tagSlugById[r.fields[1]];
      if (slug == null || slug.isEmpty) continue;
      tagsByPost.putIfAbsent(r.fields[0], () => <String>[]).add(slug);
    }

    final posts = <ArticleModel>[];
    for (final r in parseTable(sql, 'public.posts', 30)) {
      if (r.fields[_postStatus] != 'published') continue;
      posts.add(seedToArticle(
        r,
        author: authors[r.fields[_postAuthorId]],
        category: categories[r.fields[_postCategoryId]],
        tags: tagsByPost[r.id] ?? const [],
      ));
    }
    return SeedData(
      categories: categories.values.toList(),
      authors: authors.values.toList(),
      publishedPosts: posts,
    );
  }

  static ArticleModel seedToArticle(
    SeedRow post, {
    AuthorModel? author,
    CategoryModel? category,
    List<String> tags = const [],
  }) {
    final f = post.fields;
    String text(int i) => nz(f[i]) ?? '';
    final publishedAt = DateTime.parse(f[_postPublishedAt]);
    return ArticleModel(
      id: f[_postId],
      slug: f[_postSlug],
      title: text(_postTitle),
      excerpt: text(_postExcerpt),
      content: text(_postContent),
      categorySlug: category?.slug ?? '',
      categoryName: category?.name ?? '',
      subcategory: text(_postSubcategory),
      tags: tags,
      author: author ?? blankAuthor(),
      publishedAt: publishedAt,
      updatedAt: DateTime.parse(f[_postUpdatedAt]),
      featuredImage:
          text(_postFeaturedImage).isNotEmpty ? text(_postFeaturedImage) : text(_postThumbnail),
      readingTimeMinutes: int.tryParse(f[_postReadingTime]) ?? 5,
      status: ArticleStatus.values.firstWhere(
        (s) => s.name == f[_postStatus],
        orElse: () => ArticleStatus.published,
      ),
      isFeatured: f[_postIsFeatured] == 'true',
      isTrending: f[_postIsTrending] == 'true',
      isPopular: f[_postIsPopular] == 'true',
      viewCount: int.tryParse(f[_postViewCount]) ?? 0,
      keyTakeaways: decodeStringList(f[_postKeyTakeaways]),
      faqs: decodeFaqs(f[_postFaqs]),
      toc: decodeToc(f[_postToc]),
      seoTitle: text(_postSeoTitle),
      seoDescription: text(_postSeoDescription),
      canonicalUrl: text(_postCanonicalUrl),
      ogTitle: text(_postOgTitle),
      ogDescription: text(_postOgDescription),
      ogImage: text(_postOgImage),
    );
  }

  static CategoryModel seedToCategory(SeedRow row) {
    final f = row.fields;
    String text(int i) => nz(f[i]) ?? '';
    return CategoryModel(
      id: f[0],
      slug: f[3],
      name: text(2),
      description: text(4),
      iconCode: text(6),
      subcategories: decodeStringList(f[7]),
      imageUrl: text(5),
      sortOrder: int.tryParse(f[8]) ?? 0,
      isActive: f[9] != 'false',
      seoTitle: text(10),
      seoDescription: text(11),
    );
  }

  static AuthorModel seedToAuthor(SeedRow row) {
    final f = row.fields;
    final social = decodeMap(f[8]);
    // Mirrors `SupabaseArticleRepository.rowToAuthor` exactly: `designation`
    // only falls back when the column is NULL, and isActive/linkedUserId are
    // left at their defaults because the runtime mapper never reads them.
    return AuthorModel(
      id: f[0],
      slug: f[4],
      name: f[3],
      role: nz(f[7]) ?? 'Tech Writer',
      bio: nz(f[5]) ?? '',
      avatarUrl: nz(f[6]) ?? '',
      twitter: (social['twitter'] ?? '').toString(),
      linkedin: (social['linkedin'] ?? '').toString(),
      email: (social['email'] ?? '').toString(),
    );
  }

  /// A SQL `NULL` parsed out of the seed is the bare token `NULL`; every other
  /// value is text.
  static String? nz(String field) => field == 'NULL' ? null : field;

  static AuthorModel blankAuthor() => const AuthorModel(
        id: '',
        slug: '',
        name: '',
        role: '',
        bio: '',
        avatarUrl: '',
        twitter: '',
        linkedin: '',
        email: '',
      );

  static List<String> decodeStringList(String raw) {
    if (raw.isEmpty || raw == 'NULL') return const [];
    try {
      final decoded = jsonDecode(raw);
      if (decoded is! List) return const [];
      return decoded.map((e) => e.toString()).toList();
    } on FormatException {
      // `ARRAY['a','b']::text[]` and other non-JSON SQL literals: pull the
      // quoted items instead of failing the whole run.
      return RegExp("'([^']*)'").allMatches(raw).map((m) => m.group(1)!).toList();
    }
  }

  static Map<String, dynamic> decodeMap(String raw) {
    if (raw.isEmpty || raw == 'NULL') return const {};
    try {
      final decoded = jsonDecode(raw);
      return decoded is Map<String, dynamic> ? decoded : const {};
    } on FormatException {
      return const {};
    }
  }

  static List<ArticleFaq> decodeFaqs(String raw) {
    if (raw.isEmpty || raw == 'NULL') return const [];
    final decoded = jsonDecode(raw);
    if (decoded is! List) return const [];
    return decoded
        .map((e) => ArticleFaq.fromJson(Map<String, dynamic>.from(e as Map)))
        .toList();
  }

  static List<ArticleTocItem> decodeToc(String raw) {
    if (raw.isEmpty || raw == 'NULL') return const [];
    final decoded = jsonDecode(raw);
    if (decoded is! List) return const [];
    return decoded
        .map((e) => ArticleTocItem.fromJson(Map<String, dynamic>.from(e as Map)))
        .toList();
  }
}

// ── HTML shells ───────────────────────────────────────────────────────────

/// Crawler shell for one published article. Metadata is produced by [SeoMeta]
/// so it is identical to what `SeoService.updateArticleSeo` writes at runtime.
String buildArticleShell(ArticleModel art) {
  final meta = SeoMeta.forArticle(art);
  return _page(
    meta: meta,
    bodyHtml: renderArticleBody(art),
  );
}

/// Crawler shell for one category listing page.
String buildCategoryShell(CategoryModel cat) {
  final meta = SeoMeta.forCategory(cat);
  return _page(meta: meta, bodyHtml: '');
}

String _page({
  required SeoMeta meta,
  String bodyHtml = '',
}) {
  final esc = escapeHtml;
  final buf = StringBuffer()
    ..writeln('<!DOCTYPE html>')
    ..writeln('<html lang="en">')
    ..writeln('<head>')
    ..writeln('<meta charset="UTF-8">')
    ..writeln('<base href="/">')
    ..writeln('<meta name="viewport" content="width=device-width, initial-scale=1.0">')
    ..writeln('<title>${esc(meta.title)}</title>')
    ..writeln('<meta name="description" content="${esc(meta.description)}">')
    ..writeln('<meta name="robots" content="${esc(meta.robots)}">')
    ..writeln('<link rel="canonical" href="${esc(meta.canonicalUrl)}">')
    ..writeln('<meta property="og:type" content="${esc(meta.ogType)}">')
    ..writeln('<meta property="og:site_name" content="${esc(SiteConfig.siteName)}">')
    ..writeln('<meta property="og:title" content="${esc(meta.title)}">')
    ..writeln('<meta property="og:description" content="${esc(meta.description)}">')
    ..writeln('<meta property="og:url" content="${esc(meta.canonicalUrl)}">')
    ..writeln('<meta property="og:image" content="${esc(meta.ogImage)}">')
    ..writeln('<meta property="og:locale" content="en_IN">')
    ..writeln('<meta name="twitter:card" content="summary_large_image">')
    ..writeln('<meta name="twitter:site" content="${esc(SiteConfig.twitterHandle)}">')
    ..writeln('<meta name="twitter:title" content="${esc(meta.title)}">')
    ..writeln('<meta name="twitter:description" content="${esc(meta.description)}">')
    ..writeln('<meta name="twitter:image" content="${esc(meta.ogImage)}">');

  meta.properties.forEach(
      (k, v) => buf.writeln('<meta property="${esc(k)}" content="${esc(v)}">'));
  meta.names.forEach(
      (k, v) => buf.writeln('<meta name="${esc(k)}" content="${esc(v)}">'));

  if (bodyHtml.isNotEmpty) {
    buf.writeln('<style>$_staticStyle</style>');
  }
  buf
    ..writeln('<link rel="icon" type="image/png" href="/favicon.png"/>')
    ..writeln('<link rel="manifest" href="/manifest.json">')
    ..writeln(jsonLdScript(meta.jsonLd))
    ..writeln('</head>')
    ..writeln('<body style="background-color: #0B0F19;">');

  if (bodyHtml.isEmpty) {
    buf.writeln(
        '<noscript>${esc(meta.title)} — enable JavaScript to read ${esc(SiteConfig.siteName)}.</noscript>');
  } else {
    // main.dart drops this node after Flutter's first frame, so a JS-capable
    // visitor never sees it next to the app.
    buf.writeln('<div id="btp-prerendered-content">$bodyHtml</div>');
  }
  buf
    ..writeln('<script src="/flutter_bootstrap.js" async></script>')
    ..writeln('</body>')
    ..writeln('</html>');
  return buf.toString();
}

/// The structured-data block for the `<head>`.
///
/// Two safety properties are load-bearing and tested in
/// `test/prerender_seo_test.dart`:
///  1. `<`, `>` and `&` are encoded as JSON escapes, so editorial text that
///     contains `</script>` cannot close the element and execute (the classic
///     JSON-LD script-tag breakout).
///  2. The element carries `id="app-seo-json-ld"`, the id `SeoDom._setJsonLd`
///     removes before injecting the runtime graph. Without it a JS-capable
///     crawler sees the same BlogPosting twice on every article.
String jsonLdScript(Map<String, dynamic> graph) =>
    '<script type="application/ld+json" id="app-seo-json-ld">'
    '${encodeJsonForScript(graph)}'
    '</script>';

/// JSON encoder that is safe to inline inside an HTML `<script>` element.
String encodeJsonForScript(Object? value) => const JsonEncoder().convert(value)
    .replaceAll('<', r'\u003c')
    .replaceAll('>', r'\u003e')
    .replaceAll('&', r'\u0026')
    // U+2028/U+2029 are legal JSON but are line terminators in JS source; some
    // parsers evaluate ld+json as JS.
    .replaceAll('\u2028', r'\u2028')
    .replaceAll('\u2029', r'\u2029');

/// The visible copy of an article shell: the same blocks `ArticleView` renders,
/// in the same order — H1, deck, byline, body, Key Takeaways, FAQ, topics.
///
/// A non-JS crawler used to receive only the H1 + excerpt + body, so the FAQ
/// answers carried by the FAQPage node appeared in the structured data but not
/// on the page — a rich-result rejection risk (Google requires FAQ content to
/// be visible).
String renderArticleBody(ArticleModel art) {
  final out = StringBuffer()
    ..writeln('<h1>${escapeHtml(art.title)}</h1>')
    ..writeln('<p>${escapeHtml(art.excerpt)}</p>');

  final byline = <String>[
    if (art.author.name.isNotEmpty) 'By ${art.author.name}',
    if (art.categoryName.isNotEmpty) art.categoryName,
    'Published ${DateFormatter.formatEditorial(art.publishedAt.toUtc())}',
    'Updated ${DateFormatter.formatEditorial(art.updatedAt.toUtc())}',
    if (art.readingTimeMinutes > 0) '${art.readingTimeMinutes} min read',
  ];
  out.writeln('<p>${escapeHtml(byline.join(' • '))}</p>');

  out.writeln(markdownToHtml(art.content));

  if (art.keyTakeaways.isNotEmpty) {
    out
      ..writeln('<h2>Key Takeaways</h2>')
      ..writeln('<ul>');
    for (final t in art.keyTakeaways) {
      out.writeln('<li>${renderInline(t)}</li>');
    }
    out.writeln('</ul>');
  }

  if (art.faqs.isNotEmpty) {
    out.writeln('<h2>Frequently Asked Questions</h2>');
    for (final f in art.faqs) {
      out
        ..writeln('<h3>${renderInline(f.question)}</h3>')
        ..writeln('<p>${renderInline(f.answer)}</p>');
    }
  }

  if (art.tags.isNotEmpty) {
    out.writeln('<p>${escapeHtml('Topics: ${art.tags.map((t) => '#$t').join(', ')}')}</p>');
  }
  return out.toString();
}

/// Escape-first renderer for the Markdown subset this CMS writes, matching the
/// block rules `ArticleView._ArticleBodyContent` applies at runtime:
///  * `###`/`##` headings (both renderers only look at the START of a block);
///  * an ordered list only when *every* line of a block is `1.`-style — so a
///    prose line such as `1) Update commitment in years, 2) service reach`
///    stays a paragraph instead of being silently rewritten into `<ol><li>`;
///  * an unordered list only when every line starts with `- `/`* `;
///  * `**bold**` and `` `code` `` inline, unpaired markers left literal.
///
/// DELIBERATELY NOT RENDERED (left as plain text, exactly like the app): tables,
/// block quotes, images, reference/inline links (a Markdown link would add an
/// `href` the editor can point anywhere, and the app shows them literally),
/// nested lists, and `1.2`-style decimals (no space after the dot, so the list
/// pattern cannot match).
String markdownToHtml(String source) {
  final out = StringBuffer();
  for (final block in source.replaceAll('\r\n', '\n').split('\n\n')) {
    final trimmed = block.trim();
    if (trimmed.isEmpty) continue;
    final lines = trimmed.split('\n').map((l) => l.trim()).toList();

    if (trimmed.startsWith('### ')) {
      out.writeln('<h3>${renderInline(trimmed.substring(4))}</h3>');
      continue;
    }
    if (trimmed.startsWith('## ')) {
      out.writeln('<h2>${renderInline(trimmed.substring(3))}</h2>');
      continue;
    }
    if (trimmed.startsWith('# ')) {
      // The app has no `#` branch and would print the marker; a heading is both
      // better for the crawler and closer to author intent.
      out.writeln('<h2>${renderInline(trimmed.substring(2))}</h2>');
      continue;
    }

    final ordered = lines
        .map((l) => RegExp(r'^(\d+)\.\s+(.+)$').firstMatch(l))
        .toList();
    if (lines.length > 1 && ordered.every((m) => m != null)) {
      final start = int.tryParse(ordered.first!.group(1)!) ?? 1;
      out.writeln(start == 1 ? '<ol>' : '<ol start="$start">');
      for (final m in ordered) {
        out.writeln('<li>${renderInline(m!.group(2)!)}</li>');
      }
      out.writeln('</ol>');
      continue;
    }

    final bullet = lines
        .map((l) => RegExp(r'^[-*]\s+(.+)$').firstMatch(l))
        .toList();
    if (lines.length > 1 && bullet.every((m) => m != null)) {
      out.writeln('<ul>');
      for (final m in bullet) {
        out.writeln('<li>${renderInline(m!.group(1)!)}</li>');
      }
      out.writeln('</ul>');
      continue;
    }

    // Plain paragraph: keep the block's line breaks, since the runtime renders
    // the whole block as one Text node whose newlines are real line breaks.
    out.writeln('<p>${lines.map(renderInline).join('<br>')}</p>');
  }
  return out.toString();
}

/// Inline Markdown on already-escaped text: only `<strong>`/`<code>` wrappers
/// are ever produced, so no editorial content can introduce markup.
String renderInline(String raw) {
  var s = escapeHtml(raw);
  s = s.replaceAllMapped(
      RegExp(r'\*\*(.+?)\*\*'), (m) => '<strong>${m.group(1)}</strong>');
  s = s.replaceAllMapped(
      RegExp(r'`([^`]+)`'), (m) => '<code>${m.group(1)}</code>');
  return s;
}

